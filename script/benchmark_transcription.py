def write_wave(path, samples):
    with wave.open(str(path), "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(16000)
        out.writeframes(samples.tobytes())


def read_wave(path):
    with wave.open(str(path)) as audio:
        assert (audio.getnchannels(), audio.getsampwidth(), audio.getframerate()) == (1, 2, 16000)
        return array.array("h", audio.readframes(audio.getnframes()))


def prepare():
    WORK.mkdir(exist_ok=True, mode=0o700)
    existing = {
        "short": Path("/tmp/opentypeless-verification/anonymous.wav"),
        "medium": Path("/tmp/opentypeless-quality-check/long-instruction.wav"),
    }
    manifest = []
    hashes = {}
    for case_id, reference, expects_speech in CASES:
        destination = WORK / (case_id + ".wav")
        if destination.exists() and expects_speech:
            existing_pcm = read_wave(destination)
            spoken_region = existing_pcm[:7 * 16000] if case_id == "speech-stop-click" else existing_pcm
            if not spoken_region or max(abs(sample) for sample in spoken_region) == 0:
                # Only remove an invalid fixture generated by this script.
                destination.unlink()
        if not destination.exists():
            if case_id in existing and existing[case_id].exists():
                shutil.copyfile(existing[case_id], destination)
            elif expects_speech:
                text_path = WORK / (case_id + ".txt")
                text_path.write_text(reference)
                aiff_path = WORK / (case_id + ".aiff")
                subprocess.run(["/usr/bin/say", "-v", "Tingting", "-r", "205", "-f", str(text_path), "-o", str(aiff_path)], check=True)
                subprocess.run(["/usr/bin/afconvert", "-f", "WAVE", "-d", "LEI16@16000", "-c", "1", str(aiff_path), str(destination)], check=True)
                if not read_wave(destination):
                    raise RuntimeError("macOS speech synthesis produced no audio; do not benchmark this fixture.")
            if case_id == "speech-stop-click":
                spoken = read_wave(destination)
                if len(spoken) > 7 * 16000:
                    raise RuntimeError("Short-tail phrase unexpectedly exceeds seven seconds.")
                # A speech chunk ends at 8s, followed by 40ms of non-speech energy.
                samples = spoken + array.array("h", [0]) * (8 * 16000 - len(spoken))
                samples.extend(5200 if i % 2 else -5200 for i in range(640))
                samples.extend([0] * 292)
                write_wave(destination, samples)
            elif case_id == "silence-click":
                samples = array.array("h", [0]) * 70342
                for start in (80, 67200):
                    for i in range(640):
                        samples[start+i] = 2400 if i % 2 else -2400
                write_wave(destination, samples)
        pcm = read_wave(destination)
        manifest.append({"id": case_id, "path": str(destination), "reference": reference, "expectsSpeech": expects_speech})
        hashes[case_id] = {"sha256": hashlib.sha256(destination.read_bytes()).hexdigest(), "seconds": len(pcm) / 16000}
        print("FIXTURE", case_id, hashes[case_id], flush=True)
    manifest_path = WORK / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2))
    (WORK / "fixture-hashes.json").write_text(json.dumps(hashes, indent=2))
    return manifest_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--prepare-only", action="store_true")
    mode.add_argument("--run", action="store_true")
    parser.add_argument("--report", type=Path, default=WORK / "results.json")
    args = parser.parse_args()
    if args.run and args.report.exists():
        raise SystemExit("Report already exists. Review it before choosing a new report path; refusing accidental duplicate paid runs.")
    manifest = prepare()
    subprocess.run(["swift", "build", "--product", "TranscriptionBenchmark"], cwd=ROOT, check=True)
    binary_dir = subprocess.check_output(["swift", "build", "--show-bin-path"], cwd=ROOT, text=True).strip()
    binary = Path(binary_dir) / "TranscriptionBenchmark"
    subprocess.run([str(binary), "--prepare", str(manifest), str(args.report)], check=True)
    if args.prepare_only:
        return
    credential = subprocess.run(["/usr/bin/security", "find-generic-password", "-s", "com.opentypeless.mac.openrouter", "-a", "api-key", "-w"], capture_output=True, timeout=15)
    if credential.returncode or not credential.stdout.strip():
        raise SystemExit("The app's existing Keychain credential could not be read. No benchmark requests sent.")
    run = subprocess.Popen([str(binary), "--run", str(manifest), str(args.report)], stdin=subprocess.PIPE)
    try:
        run.communicate(input=credential.stdout.strip() + b"\n")
    finally:
        if run.poll() is None:
            run.terminate()
    raise SystemExit(run.returncode)


if __name__ == "__main__":
    main()
